/**
 * The wallpaper group p6m (*632) on the Eisenstein lattice.
 *
 * Part of `core/symmetry`, after the affine maps and group type of step 2.1 and
 * before orbit tiling (`orbit.ts`). It supplies the generators and a membership
 * test; gadgets and motifs are tiled by applying these maps. Everything is
 * exact integer arithmetic.
 *
 * Reference: Conway, Burgiel & Goodman-Strauss, "The Symmetries of Things",
 * ch. 6 (the orbifold *632); Armstrong, "Groups and Symmetry", ch. 25–26
 * (wallpaper groups as semidirect products).
 */

import { conj, eis, mul, norm, OMEGA, ONE, type Eisenstein } from "../lattice/eisenstein";
import { reflection, rotation60, translation, type Affine } from "./affine";
import { affineGroup, closure } from "./group";

/**
 * A p6m group with translation lattice πΛ, where Λ = ℤ[ω].
 *
 * Every element is z ↦ g(z) + λ with g in `pointGroup` and λ in πΛ.
 */
export type P6m = {
  /** The period π; the translation lattice is πΛ. */
  readonly period: Eisenstein;
  /** The point group D6 fixing the origin (12 maps, identity first). */
  readonly pointGroup: readonly Affine[];
  /** Generators: rotation by 60°, reflection, and translations by π and πω. */
  readonly generators: readonly Affine[];
};

/**
 * Returns true when z lies in the lattice πΛ.
 *
 * Formula: z ∈ πΛ ⇔ z/π ∈ ℤ[ω]. Since 1/π = π̄/N(π), this holds iff both
 * coordinates of z·π̄ are divisible by N(π). Integer-only, so it is exact.
 *
 * @param z - lattice point
 * @param period - π, nonzero
 * @throws RangeError if π is zero
 */
export function inLattice(z: Eisenstein, period: Eisenstein): boolean {
  const n = norm(period);
  if (n === 0) throw new RangeError("inLattice period must be nonzero");
  const w = mul(z, conj(period));
  return w.a % n === 0 && w.b % n === 0;
}

/**
 * Builds p6m with translation lattice πΛ.
 *
 * p6m = πΛ ⋊ D6 is a group only when D6 preserves πΛ. Rotation always does
 * (πΛ is an ideal of ℤ[ω]). The reflection z ↦ z̄ maps πΛ to π̄Λ, so it
 * preserves πΛ iff π̄ ∈ πΛ (equal norms then make them associates). Otherwise
 * the generated group is not p6m, so we reject the period.
 *
 * @param period - π; defaults to 1 (unit cell of the triangular lattice)
 * @throws RangeError if π is zero or πΛ is not mirror-symmetric
 */
export function p6m(period: Eisenstein = ONE): P6m {
  if (norm(period) === 0) throw new RangeError("p6m period must be nonzero");
  if (!inLattice(conj(period), period)) {
    throw new RangeError(
      `Lattice generated by (${period.a}, ${period.b}) is not mirror-symmetric, so the group is p6, not p6m`,
    );
  }
  const r = rotation60(1);
  const s = reflection();
  return {
    period: eis(period.a, period.b),
    pointGroup: closure(affineGroup, [r, s], 12),
    generators: [r, s, translation(period), translation(mul(period, OMEGA))],
  };
}

/**
 * Returns true when f is an element of the group.
 *
 * Formula: f(z) = M z + t belongs to πΛ ⋊ D6 iff M is a point-group matrix and
 * t ∈ πΛ (semidirect-product description of the group).
 */
export function contains(group: P6m, f: Affine): boolean {
  return (
    group.pointGroup.some((g) => g.m.every((v, i) => v === f.m[i])) && inLattice(f.t, group.period)
  );
}
