/**
 * Symmetric random pleat orientations: the "random motif with symmetry" of step 8.2.
 *
 * Sits in Phase 8 after `shrink-rotate.ts`: it groups the tessellation's tiling edges into orbits
 * under a rotation about the origin (and optionally a lattice translation), and draws one random
 * orientation per orbit, so the pattern the M/V solver then completes has that symmetry.
 *
 * Only rotations are used. The shrink-rotate map is chiral, so a mirror takes the tessellation to
 * the other hand, not to itself (the same reason the star twist has no mirror symmetry).
 */

import { eis, mul, OMEGA, type Eisenstein } from "../lattice/eisenstein";
import { apply, rotation60, translation, type Affine } from "../symmetry/affine";
import { TILING_SCALE, type ShrinkRotated } from "./shrink-rotate";

/** The tiling edges that one random choice decides: each member has the orbit's value, or its opposite. */
export type EdgeOrbit = {
  /** Indices into `ShrinkRotated.interior`, with `flip` true when the member takes the opposite value. */
  readonly members: readonly { readonly edge: number; readonly flip: boolean }[];
};

const key = (z: Eisenstein): string => `${z.a},${z.b}`;

/**
 * Groups the interior tiling edges into orbits of the symmetry generated by a rotation about the
 * origin and, optionally, translations by a lattice vector and its ω-multiple.
 *
 * A rotation is an orientation-preserving isometry, so it keeps a crease's mountain or valley: it
 * maps the pleat (tile f, tile g) to the pleat (r f, r g), and a member whose image lists the tiles
 * in the other order takes the opposite value. An orbit whose images disagree with themselves (a
 * half turn about an edge midpoint swaps the two tiles of that edge) has no symmetric assignment, and
 * is rejected. Edges whose image falls outside the window are ignored, so translations only link
 * the edges that stay inside.
 *
 * @param sr - the tessellation
 * @param symmetry - `rotation` is the order of the rotation about the origin (1, 2, 3 or 6);
 *   `period`, in unit lattice steps, adds translations by period and period·ω
 * @throws RangeError for an unsupported order, a rotation that is not a symmetry of the tessellation
 *   (its tile set must be invariant, so a grown region that is not symmetric is rejected too), or
 *   an orbit with no symmetric assignment
 */
export function edgeOrbits(
  sr: ShrinkRotated,
  symmetry: { readonly rotation: 1 | 2 | 3 | 6; readonly period?: Eisenstein },
): EdgeOrbit[] {
  if (![1, 2, 3, 6].includes(symmetry.rotation)) {
    throw new RangeError(`Rotation order must be 1, 2, 3 or 6, got ${symmetry.rotation}`);
  }
  const generators: Affine[] = [];
  if (symmetry.rotation > 1) generators.push(rotation60(6 / symmetry.rotation));
  if (symmetry.period !== undefined) {
    const t = eis(symmetry.period.a * TILING_SCALE, symmetry.period.b * TILING_SCALE);
    generators.push(translation(t), translation(mul(t, OMEGA)));
  }

  const edgeAt = new Map<string, number>();
  const tileAt = new Map<string, number>();
  const sortedKey = (corners: readonly Eisenstein[]): string => corners.map(key).sort().join("|");
  sr.tiles.forEach((tile, f) => tileAt.set(sortedKey(tile), f));
  sr.interior.forEach((e, j) => edgeAt.set(sortedKey(e.ends), j));

  const parent = sr.interior.map((_, j) => j);
  const parity = sr.interior.map(() => false);
  const find = (j: number): { root: number; flip: boolean } => {
    let flip = false;
    let at = j;
    while (parent[at] !== at) {
      flip = flip !== parity[at]!;
      at = parent[at]!;
    }
    return { root: at, flip };
  };
  const link = (a: number, b: number, flip: boolean): void => {
    const x = find(a);
    const y = find(b);
    if (x.root === y.root) {
      if ((x.flip !== y.flip) !== flip) {
        throw new RangeError(`Edge ${a} has no symmetric assignment under this symmetry`);
      }
      return;
    }
    parent[x.root] = y.root;
    parity[x.root] = (x.flip !== y.flip) !== flip;
  };

  sr.interior.forEach((e, j) => {
    for (const g of generators) {
      const image = e.ends.map((z) => apply(g, z));
      const target = edgeAt.get(sortedKey(image));
      if (target === undefined) {
        if (g.t.a === 0 && g.t.b === 0) {
          throw new RangeError("The rotation is not a symmetry of the tiling about the origin");
        }
        continue;
      }
      const tiles = e.tiles.map((f) => tileAt.get(sortedKey(sr.tiles[f]!.map((z) => apply(g, z)))));
      const t = sr.interior[target]!;
      if (tiles[0] === undefined || tiles[1] === undefined) {
        throw new RangeError("The symmetry maps a tile outside the window");
      }
      link(j, target, tiles[0] !== t.tiles[0]);
    }
  });

  const groups = new Map<number, { edge: number; flip: boolean }[]>();
  sr.interior.forEach((_, j) => {
    const { root, flip } = find(j);
    const list = groups.get(root) ?? [];
    list.push({ edge: j, flip });
    groups.set(root, list);
  });
  return [...groups.values()].map((members) => Object.freeze({ members: Object.freeze(members) }));
}

/**
 * A small seeded generator (Mulberry32) returning floats in [0, 1).
 *
 * For reproducible generation and tests only: it is not a statistical or cryptographic generator.
 *
 * @param seed - any 32-bit integer; other numbers are reduced as `seed >>> 0` (a fraction is truncated,
 *   NaN is 0, and a seed and its shift by 2³² give the same stream)
 */
export function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Draws one random Boolean per orbit and spreads it over the orbit's members.
 *
 * @param orbits - from {@link edgeOrbits}
 * @param count - the number of interior edges (`sr.interior.length`)
 * @param rng - a generator returning floats in [0, 1)
 * @returns `mountainOnFirst` for {@link orientedPattern}
 */
export function randomOrientation(
  orbits: readonly EdgeOrbit[],
  count: number,
  rng: () => number,
): boolean[] {
  const out = Array<boolean>(count).fill(false);
  for (const orbit of orbits) {
    const value = rng() < 0.5;
    for (const { edge, flip } of orbit.members) out[edge] = value !== flip;
  }
  return out;
}
